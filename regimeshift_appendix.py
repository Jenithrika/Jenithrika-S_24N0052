def bootstrap_sharpe(net_ret_series, n_boot=2000, block_size=20, seed=42):
    print("\n" + "=" * 80)
    print("BLOCK-BOOTSTRAP SHARPE CONFIDENCE INTERVALS")
    print("=" * 80)
    # 104 raw regime transitions over one historical path is thin sampling
    # variety for ranking strategies on point estimates alone.

    rng = np.random.default_rng(seed)
    compare = {k: v for k, v in net_ret_series.items()
               if k in ("Dynamic (Regime, hysteresis)", "Equal Weight", "Static 60/40")}

    for name, ret in compare.items():
        r = ret.values
        n = len(r)
        n_blocks = int(np.ceil(n / block_size))
        boot_sharpes = np.empty(n_boot)
        for b in range(n_boot):
            starts = rng.integers(0, n - block_size, size=n_blocks)
            sample = np.concatenate([r[s:s + block_size] for s in starts])[:n]
            ann_ret = sample.mean() * 252
            ann_vol = sample.std() * np.sqrt(252)
            boot_sharpes[b] = ann_ret / ann_vol if ann_vol > 0 else np.nan
        lo, hi = np.nanpercentile(boot_sharpes, [5, 95])
        point = r.mean() * 252 / (r.std() * np.sqrt(252))
        print(f"  {name:32s}: point Sharpe={point:.3f}  90% CI=[{lo:.3f}, {hi:.3f}]")


