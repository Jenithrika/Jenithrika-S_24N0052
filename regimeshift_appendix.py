def fit_hmm_multi_restart(X_scaled, n_states, n_restarts, n_iter=1000):
    best_model, best_score = None, -np.inf
    for seed in range(n_restarts):
        candidate = GaussianHMM(n_components=n_states, covariance_type="diag",
                                 n_iter=n_iter, tol=1e-4, random_state=seed)
        candidate.fit(X_scaled)
        score = candidate.score(X_scaled)
        if score > best_score:
            best_score, best_model = score, candidate
    return best_model, best_score


def derive_label_map(X_raw_train, hidden_states_train, n_states):
    stats = X_raw_train.groupby(hidden_states_train).mean()
    present_states = stats.index.tolist()
    if len(present_states) < n_states:
        vol_rank = stats["vol_21d"].sort_values(ascending=False)
        return {s: (["Crisis", "Bear", "Bull"][i] if i < 3 else f"State{s}")
                for i, s in enumerate(vol_rank.index)}
    vol_rank = stats["vol_21d"].sort_values(ascending=False)
    crisis_state = vol_rank.index[0]
    remaining = [s for s in present_states if s != crisis_state]
    if stats.loc[remaining[0], "drawdown_126d"] <= stats.loc[remaining[1], "drawdown_126d"]:
        bear_state, bull_state = remaining[0], remaining[1]
    else:
        bear_state, bull_state = remaining[1], remaining[0]
    return {bull_state: "Bull", bear_state: "Bear", crisis_state: "Crisis"}


def phase3_global_hmm(features):
    print("\n" + "=" * 80)
    print("PHASE 3: GLOBAL HMM FIT (diagnostic only)")
    print("=" * 80)

    X_raw = features[SELECTED_FEATURES].copy()
    mu, sigma = X_raw.mean(), X_raw.std()
    X_values = ((X_raw - mu) / sigma).values

    model, score = fit_hmm_multi_restart(X_values, N_STATES, N_RESTARTS_GLOBAL)
    hidden_states = model.predict(X_values)
    label_map = derive_label_map(X_raw, hidden_states, N_STATES)

    stats = X_raw.groupby(hidden_states).mean()
    print(f"Label mapping: {label_map}")

    bear_state = [s for s, lbl in label_map.items() if lbl == "Bear"][0]
    bear_mom, bear_dd = stats.loc[bear_state, "mom_63d"], stats.loc[bear_state, "drawdown_126d"]
    if bear_mom > -0.02 and bear_dd > -0.08:
        print(f"[NOTE] Bear state (mom_63d={bear_mom:+.3f}, drawdown_126d={bear_dd:+.2%}) "
              f"looks closer to 'choppy' than a genuine decline -- see BEAR_RISK_AVERSION.")

    regime = pd.Series(hidden_states, index=X_raw.index).map(label_map)
    regime.name = "regime"
    return regime


