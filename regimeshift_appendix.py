def run_backtest_with_holdings(returns_df, target_weights_df, rebalance_flags, cost_bps):
    """Same as run_backtest but also records the actually-held weight each day,
    needed to check whether held equity exposure lags the price recovery (H2)."""
    idx = returns_df.index
    n_ = len(idx)
    net_ret = np.zeros(n_)
    turnover = np.zeros(n_)
    held = target_weights_df.iloc[0].values.copy()
    held_history = np.zeros((n_, len(ASSETS)))

    for t in range(n_):
        if rebalance_flags.iloc[t]:
            target = target_weights_df.iloc[t].values
            turnover[t] = 0.5 * np.sum(np.abs(target - held))
            held = target.copy()

        held_history[t] = held
        cost = turnover[t] * (cost_bps / 10000.0)
        simple_r = np.exp(returns_df.iloc[t].values) - 1.0
        port_simple_r = np.dot(held, simple_r)
        net_ret[t] = np.log(max(1 + port_simple_r - cost, 1e-8))

        drifted = held * (1 + simple_r)
        held = drifted / drifted.sum()

    held_df = pd.DataFrame(held_history, index=idx, columns=ASSETS)
    return pd.Series(net_ret, index=idx, name="net_log_ret"), pd.Series(turnover, index=idx, name="turnover"), held_df


def diag_C_recovery_lag(log_returns, regime_wf, prices, target_dynamic_confirmed, regime_bt_confirmed,
                         returns_bt, valid_idx, lookback_days=150, sample_every=10):
    print("\n" + "=" * 80)
    print("[DEEP DIVE C] RECOVERY-LAG DIAGNOSTIC -- does held equity exposure lag price?")
    print("=" * 80)

    _, rebal_confirmed = build_dynamic_targets(returns_bt, regime_bt_confirmed, valid_idx)
    net_ret, turnover, held_df = run_backtest_with_holdings(
        returns_bt, target_dynamic_confirmed, rebal_confirmed, REPORT_COST_BPS
    )
    equity_curve = np.exp(net_ret.cumsum())

    post2020 = equity_curve.loc["2021-01-01":]
    running_max = post2020.cummax()
    drawdown = post2020 / running_max - 1.0
    trough_date = drawdown.idxmin()
    peak_date = post2020.loc[:trough_date].idxmax()
    print(f"Largest post-2020 drawdown for Dynamic (hysteresis): {drawdown.min():.2%}, "
          f"peak {peak_date.date()} -> trough {trough_date.date()}")

    nifty = prices["equity"].reindex(equity_curve.index)
    window_end = min(trough_date + pd.tseries.offsets.BDay(lookback_days), equity_curve.index.max())
    window_idx = equity_curve.loc[trough_date:window_end].index[::sample_every]

    nifty_at_trough = nifty.loc[trough_date]
    rows = []
    for d in window_idx:
        rows.append({
            "date": d.date(),
            "days_since_trough": (d - trough_date).days,
            "regime": regime_bt_confirmed.reindex([d]).iloc[0] if d in regime_bt_confirmed.index else None,
            "held_equity_wt": held_df.loc[d, "equity"] if d in held_df.index else np.nan,
            "target_equity_wt": target_dynamic_confirmed.loc[d, "equity"] if d in target_dynamic_confirmed.index else np.nan,
            "nifty_indexed": 100 * nifty.loc[d] / nifty_at_trough if d in nifty.index else np.nan,
        })
    recovery_df = pd.DataFrame(rows).set_index("date")
    print(f"\nTrajectory from trough ({trough_date.date()}) through +{lookback_days} trading days:")
    print(recovery_df.round(3))

    print("\nnifty_indexed climbing while held_equity_wt stays flat/low = H2 (timing lag). "
          "held_equity_wt tracking target_equity_wt but both staying low even in Bull = H1 "
          "(cap/shrinkage ceiling), not a lag problem.")
    return recovery_df


