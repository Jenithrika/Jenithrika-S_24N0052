def run_backtest_with_holdings(returns_df, target_weights_df, rebalance_flags, cost_bps):
    """Same as run_backtest but also records the actually-held weight each day,
    needed to check whether held equity exposure lags the price recovery (H2)."""
    idx = returns_df.index
    n_ = len(idx)
    net_ret = np.zeros(n_)
    turnover = np.zeros(n_)
    held = target_weights_df.iloc[0].values.copy()
    held_history = np.zeros((n_, len(ASSETS)))

    for t in range(n_):
        if rebalance_flags.iloc[t]:
            target = target_weights_df.iloc[t].values
            turnover[t] = 0.5 * np.sum(np.abs(target - held))
            held = target.copy()

        held_history[t] = held
        cost = turnover[t] * (cost_bps / 10000.0)
        simple_r = np.exp(returns_df.iloc[t].values) - 1.0
        port_simple_r = np.dot(held, simple_r)
        net_ret[t] = np.log(max(1 + port_simple_r - cost, 1e-8))

        drifted = held * (1 + simple_r)
        held = drifted / drifted.sum()

    held_df = pd.DataFrame(held_history, index=idx, columns=ASSETS)
    return pd.Series(net_ret, index=idx, name="net_log_ret"), pd.Series(turnover, index=idx, name="turnover"), held_df


