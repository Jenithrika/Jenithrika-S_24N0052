# PHASE 5 -- PORTFOLIO OPTIMIZATION MACHINERY (shared with phase 6/7)
# ==============================================================================

def shrink_cov(cov, shrinkage=COV_SHRINKAGE):
    return (1 - shrinkage) * cov + shrinkage * np.diag(np.diag(cov))


def shrink_mu(mu, shrinkage=MU_SHRINKAGE):
    return (1 - shrinkage) * mu + shrinkage * np.mean(mu)


def _weight_constraints(w):
    c = [cp.sum(w) == 1, w >= 0]
    if WEIGHT_CAP is not None:
        c.append(w <= WEIGHT_CAP)
    return c


def solve_max_sharpe(mu, cov, rf=RF_DAILY):
    n_ = len(mu)
    excess = mu - rf
    if not np.any(excess > 1e-8):
        return None
    y = cp.Variable(n_)
    kappa = cp.Variable(nonneg=True)
    constraints = [cp.sum(y) == kappa, excess @ y == 1, kappa >= 1e-6, y >= 0]
    if WEIGHT_CAP is not None:
        constraints.append(y <= WEIGHT_CAP * kappa)  # w = y/kappa <= WEIGHT_CAP
    try:
        cp.Problem(cp.Minimize(cp.quad_form(y, cp.psd_wrap(cov))), constraints).solve()
    except cp.error.SolverError:
        return None
    if y.value is None or kappa.value is None or kappa.value < 1e-8:
        return None
    w = np.clip(y.value / kappa.value, 0, None)
    return w / w.sum()


def solve_min_variance(mu, cov):
    w = cp.Variable(len(mu))
    try:
        cp.Problem(cp.Minimize(cp.quad_form(w, cp.psd_wrap(cov))), _weight_constraints(w)).solve()
        return w.value
    except cp.error.SolverError:
        return None


def solve_balanced(mu, cov, risk_aversion):
    w = cp.Variable(len(mu))
    try:
        cp.Problem(cp.Maximize(mu @ w - risk_aversion * cp.quad_form(w, cp.psd_wrap(cov))),
                   _weight_constraints(w)).solve()
        return w.value
    except cp.error.SolverError:
        return None


def bull_solver(mu, cov):
    w = solve_max_sharpe(mu, cov)
    return w if w is not None else solve_balanced(mu, cov, risk_aversion=BULL_FALLBACK_RISK_AVERSION)


REGIME_SOLVERS = {
    "Bull": bull_solver,
    "Bear": lambda mu, cov: solve_balanced(mu, cov, risk_aversion=BEAR_RISK_AVERSION),
    "Crisis": lambda mu, cov: solve_min_variance(mu, cov),
}

INVERSION_LOG = []  # refits where Crisis ends up MORE exposed to equity than Bull


def compute_regime_weights(returns_slice, regime_slice, log_inversions=False):
    weights = {}
    for regime in REGIME_ORDER:
        mask = regime_slice == regime
        w = None
        if mask.sum() >= MIN_DAYS_FOR_COV:
            r = returns_slice.loc[mask]
            mu = shrink_mu(r.mean().values)
            cov = shrink_cov(r.cov().values)
            w = REGIME_SOLVERS[regime](mu, cov)
        weights[regime] = w if w is not None else np.repeat(1 / len(ASSETS), len(ASSETS))

    if log_inversions and weights["Bull"] is not None and weights["Crisis"] is not None:
        eq_idx = ASSETS.index("equity")
        if weights["Crisis"][eq_idx] > weights["Bull"][eq_idx]:
            INVERSION_LOG.append({
                "bull_equity": weights["Bull"][eq_idx],
                "crisis_equity": weights["Crisis"][eq_idx],
                "regime_days": {r: int((regime_slice == r).sum()) for r in REGIME_ORDER},
            })
    return weights


